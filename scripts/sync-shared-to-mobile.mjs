#!/usr/bin/env node
// Sync the workspace's `shared/src/` package into `mobile/src/_shared/`.
//
// Why: EAS Build doesn't reliably resolve pnpm workspace dependencies
// (uploads only `mobile/` and can't find `@money-nest/shared`). Vendoring
// the shared code into the mobile project sidesteps the issue entirely —
// mobile becomes self-contained for Expo builds while the web app keeps
// using the workspace package via Vercel's better pnpm support.
//
// Run this before any EAS build if you've edited `shared/src/*`:
//   node scripts/sync-shared-to-mobile.mjs
//
// The vendored files contain a "DO NOT EDIT" banner so contributors edit
// the source in `shared/` instead of drifting the mobile copy.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\//, "");
const src = join(root, "shared", "src");
const dst = join(root, "mobile", "src", "_shared");

const BANNER = `// AUTO-GENERATED from shared/src/ by scripts/sync-shared-to-mobile.mjs
// DO NOT EDIT this file directly — edit shared/src/ and re-run the sync
// script. The mobile app reads its copy from here because EAS Build
// can't resolve the workspace package on its end.

`;

function walk(dir, base = "") {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const rel = base ? `${base}/${name}` : name;
    if (statSync(full).isDirectory()) {
      mkdirSync(join(dst, rel), { recursive: true });
      walk(full, rel);
    } else if (name.endsWith(".ts")) {
      const content = readFileSync(full, "utf8");
      writeFileSync(join(dst, rel), BANNER + content, "utf8");
      console.log(`  ${rel}`);
    }
  }
}

mkdirSync(dst, { recursive: true });
console.log("Syncing shared/src → mobile/src/_shared:");
walk(src);
console.log("Done.");
